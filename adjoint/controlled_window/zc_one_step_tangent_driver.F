C=======================================================================
C Advance one explicit ZC state and one REAL tangent by one coupled step.
C The generated run23 tangent kernel is unchanged; this is only a thin
C compositional driver for controls inserted between authentic steps.
C=======================================================================
      PROGRAM ZC_ONE_STEP_TANGENT_DRIVER
      INCLUDE 'zc_kernel_state.inc'
      INCLUDE 'zeq.common'
      INCLUDE 'modified_means.common'

      REAL STATE_R_IN(ZC_STATE_NREAL),STATE_R_IND(ZC_STATE_NREAL)
      REAL STATE_R_OUT(ZC_STATE_NREAL),STATE_R_OUTD(ZC_STATE_NREAL)
      COMPLEX STATE_C_IN(ZC_STATE_NCOMPLEX)
      COMPLEX STATE_C_OUT(ZC_STATE_NCOMPLEX)
      REAL*8 STATE_D_IN(ZC_STATE_NDOUBLE),STATE_D_OUT(ZC_STATE_NDOUBLE)
      INTEGER STATE_I_IN(ZC_STATE_NINTEGER),STATE_I_OUT(ZC_STATE_NINTEGER)
      REAL STATE_TIME_IN(ZC_STATE_NTIME),STATE_TIME_OUT(ZC_STATE_NTIME)
      INTEGER TAPE(ZC_TAPE_WIDTH,1)
      INTEGER NSTART,NT_RESTART,NATMR,IT1,IOS
      REAL TFIND,TD_RESTART,TZERO_RESTART
      LOGICAL ZC_KERNEL_MODE
      COMMON/commTIME/IT,MP,TY
      COMMON/IST/ist
      COMMON/STRPAR/RSTR,TCUT,TSEED,TAMP1,TAMP2,JLEFT,JRT,ITOP,
     A IBOT,NIC
      COMMON/zc_kernel_mode/ZC_KERNEL_MODE
      CHARACTER*1 HEADER_LOCAL(80)
      CHARACTER*512 INPUT_FILE,DIRECTION_FILE,OUTPUT_FILE,JVP_FILE
      CHARACTER*512 TAPE_FILE

      INPUT_FILE=' '
      DIRECTION_FILE=' '
      OUTPUT_FILE=' '
      JVP_FILE=' '
      TAPE_FILE=' '
      CALL GET_COMMAND_ARGUMENT(1,INPUT_FILE)
      CALL GET_COMMAND_ARGUMENT(2,DIRECTION_FILE)
      CALL GET_COMMAND_ARGUMENT(3,OUTPUT_FILE)
      CALL GET_COMMAND_ARGUMENT(4,JVP_FILE)
      CALL GET_COMMAND_ARGUMENT(5,TAPE_FILE)
      IF(LEN_TRIM(INPUT_FILE).EQ.0) INPUT_FILE='kernel_input_state.bin'
      IF(LEN_TRIM(DIRECTION_FILE).EQ.0)
     A DIRECTION_FILE='tangent_direction.bin'
      IF(LEN_TRIM(OUTPUT_FILE).EQ.0) OUTPUT_FILE='kernel_output_state.bin'
      IF(LEN_TRIM(JVP_FILE).EQ.0) JVP_FILE='tangent_jv.bin'
      IF(LEN_TRIM(TAPE_FILE).EQ.0) TAPE_FILE='kernel_one_step_tape.bin'

      ZC_KERNEL_MODE=.TRUE.
      iprint_namelists=0
      ist=0
      OPEN(5,FILE='fc.data',STATUS='OLD',IOSTAT=IOS)
      IF(IOS.NE.0) THEN
         WRITE(*,*) 'ERROR: cannot open fc.data; IOSTAT=',IOS
         STOP 2
      ENDIF
      READ(5,450) HEADER_LOCAL
 450  FORMAT(80A1)
      CALL OPENFL
      NATM=2
      READ(5,40,END=999) NSTART,TFIND
 40   FORMAT(8X,I15/8X,F15.0)
      IF(NSTART.NE.3) THEN
         WRITE(*,*) 'ERROR: tangent step driver requires NSTART=3'
         STOP 2
      ENDIF
      CALL RDHIST(0,TFIND)
      TD_RESTART=TD
      NT_RESTART=NT
      TZERO_RESTART=TZERO
      NATMR=NATM
      CALL SETUP
      TD=TD_RESTART
      NT=NT_RESTART
      TZERO=TZERO_RESTART
      IT1=TD+120.501
      IT=MOD(IT1,12)
      MP=IT+1
      IF(IT.EQ.0) IT=12
      TY=TD+120.501-IT1
      CALL SETUP2
      CALL INITDAT
      CALL CONSTC
      IF(NIC.NE.0) THEN
         WRITE(*,*) 'ERROR: tangent step driver requires NIC=0'
         STOP 2
      ENDIF

      CALL ZC_CWT_READ_STATE(TRIM(INPUT_FILE),STATE_R_IN,STATE_C_IN,
     A STATE_D_IN,STATE_I_IN,STATE_TIME_IN)
      CALL ZC_CWT_READ_REAL(TRIM(DIRECTION_FILE),STATE_R_IND,
     A ZC_STATE_NREAL)
      CALL ZC_KERNEL_WINDOW_D(STATE_R_IN,STATE_R_IND,STATE_C_IN,
     A STATE_D_IN,STATE_I_IN,STATE_TIME_IN,1,STATE_R_OUT,
     B STATE_R_OUTD,STATE_C_OUT,STATE_D_OUT,STATE_I_OUT,
     C STATE_TIME_OUT,TAPE)
      CALL ZC_CWT_WRITE_STATE(TRIM(OUTPUT_FILE),STATE_R_OUT,STATE_C_OUT,
     A STATE_D_OUT,STATE_I_OUT,STATE_TIME_OUT)
      CALL ZC_CWT_WRITE_REAL(TRIM(JVP_FILE),STATE_R_OUTD,
     A ZC_STATE_NREAL)
      OPEN(204,FILE=TRIM(TAPE_FILE),FORM='UNFORMATTED',
     A ACCESS='STREAM',STATUS='REPLACE')
      WRITE(204) TAPE
      CLOSE(204)
      STOP
 999  WRITE(*,*) 'ERROR: unexpected end of fc.data'
      STOP 2
      END


      SUBROUTINE ZC_CWT_READ_STATE(NAME,STATE_R,STATE_C,STATE_D,
     A STATE_I,STATE_TIME)
      INCLUDE 'zc_kernel_state.inc'
      CHARACTER*(*) NAME
      REAL STATE_R(ZC_STATE_NREAL)
      COMPLEX STATE_C(ZC_STATE_NCOMPLEX)
      REAL*8 STATE_D(ZC_STATE_NDOUBLE)
      INTEGER STATE_I(ZC_STATE_NINTEGER)
      REAL STATE_TIME(ZC_STATE_NTIME)
      INTEGER IOS
      INTEGER*8 FILE_BYTES,EXPECTED_BYTES
      LOGICAL EXISTS
      EXPECTED_BYTES=4_8*ZC_STATE_NREAL+8_8*ZC_STATE_NCOMPLEX+
     A 8_8*ZC_STATE_NDOUBLE+4_8*ZC_STATE_NINTEGER+
     B 4_8*ZC_STATE_NTIME
      INQUIRE(FILE=NAME,EXIST=EXISTS,SIZE=FILE_BYTES)
      IF(.NOT.EXISTS .OR. FILE_BYTES.NE.EXPECTED_BYTES) THEN
         WRITE(*,*) 'ERROR: invalid state-file bytes'
         STOP 2
      ENDIF
      OPEN(200,FILE=NAME,FORM='UNFORMATTED',ACCESS='STREAM',
     A STATUS='OLD',IOSTAT=IOS)
      READ(200,IOSTAT=IOS) STATE_R,STATE_C,STATE_D,STATE_I,STATE_TIME
      IF(IOS.NE.0) STOP 'cannot read state file'
      CLOSE(200)
      RETURN
      END

      SUBROUTINE ZC_CWT_READ_REAL(NAME,X,N)
      CHARACTER*(*) NAME
      REAL X(N)
      INTEGER IOS
      INTEGER*8 FILE_BYTES
      LOGICAL EXISTS
      INQUIRE(FILE=NAME,EXIST=EXISTS,SIZE=FILE_BYTES)
      IF(.NOT.EXISTS .OR. FILE_BYTES.NE.4_8*N) THEN
         WRITE(*,*) 'ERROR: invalid tangent-file bytes'
         STOP 2
      ENDIF
      OPEN(201,FILE=NAME,FORM='UNFORMATTED',ACCESS='STREAM',
     A STATUS='OLD',IOSTAT=IOS)
      READ(201,IOSTAT=IOS) X
      IF(IOS.NE.0) STOP 'cannot read tangent file'
      CLOSE(201)
      RETURN
      END

      SUBROUTINE ZC_CWT_WRITE_STATE(NAME,STATE_R,STATE_C,STATE_D,
     A STATE_I,STATE_TIME)
      INCLUDE 'zc_kernel_state.inc'
      CHARACTER*(*) NAME
      REAL STATE_R(ZC_STATE_NREAL)
      COMPLEX STATE_C(ZC_STATE_NCOMPLEX)
      REAL*8 STATE_D(ZC_STATE_NDOUBLE)
      INTEGER STATE_I(ZC_STATE_NINTEGER)
      REAL STATE_TIME(ZC_STATE_NTIME)
      OPEN(202,FILE=NAME,FORM='UNFORMATTED',ACCESS='STREAM',
     A STATUS='REPLACE')
      WRITE(202) STATE_R,STATE_C,STATE_D,STATE_I,STATE_TIME
      CLOSE(202)
      RETURN
      END

      SUBROUTINE ZC_CWT_WRITE_REAL(NAME,X,N)
      CHARACTER*(*) NAME
      REAL X(N)
      OPEN(203,FILE=NAME,FORM='UNFORMATTED',ACCESS='STREAM',
     A STATUS='REPLACE')
      WRITE(203) X
      CLOSE(203)
      RETURN
      END


C Passive helpers omitted by Tapenade because the complex FFT workspace is
C not an active input in this derivative contract.
      SUBROUTINE ZC_PACK_COMPLEX(A,N,X,K)
      COMPLEX A(N),X(*)
      DO 10 I=1,N
         X(K)=A(I)
         K=K+1
 10   CONTINUE
      RETURN
      END

      SUBROUTINE ZC_UNPACK_COMPLEX(A,N,X,K)
      COMPLEX A(N),X(*)
      DO 10 I=1,N
         A(I)=X(K)
         K=K+1
 10   CONTINUE
      RETURN
      END


C GETN is a discrete branch selector.  The tangent follows the substep count
C selected on the primal trajectory and does not differentiate the integer.
      SUBROUTINE GETN(NSST)
      INCLUDE 'zeq.common'
      COMMON/ZDATA/WM(30,34,2,12),DIVM(30,34,12),Q0O(30,34),
     A SSTM(30,34,12),UO(30,34),VO(30,34),DO(30,34),HTAU(34,30,2),
     B WEM(30,34,12),TO(30,34),UV(30,34,2,12),US(30,34),VS(30,34),
     C WP(30,34),DT1(30,34,7),TT(30,34),UV1(30,34),UV2(30,34),
     D WM1(30,34),UAT(30,34),VAT(30,34),DIVT(30,34)
      COMMON/SGRID/XWRS,DXRS,YNRS,DYRS,NYPS
      SAVE
      DX1=DXRS*1.11E7
      DY1=DYRS*1.11E7
      DTT=DTD*2.628E6
      NSST=2
      DO 20 I=6,25
         DO 10 J=6,32
            AAA=ABS(US(I,J))*DTT/DX1
            BBB=ABS(VS(I,J))*DTT/DY1
            IAA=1+AAA
            IBB=1+BBB
            NSST=MAX0(NSST,IAA)
            NSST=MAX0(NSST,IBB)
 10      CONTINUE
 20   CONTINUE
      RETURN
      END
