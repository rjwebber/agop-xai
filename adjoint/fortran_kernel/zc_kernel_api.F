      SUBROUTINE ZC_KERNEL_ADVANCE_COMMON(TAPE)
      INCLUDE 'zeq.common'
      INTEGER TAPE(3)
      INTEGER KERNEL_NSST,KERNEL_ATM_ITER,KERNEL_ATM_RESET
      LOGICAL ZC_KERNEL_MODE
      COMMON/commTIME/IT,MP,TY
      COMMON/IST/ist
      COMMON/zc_kernel_mode/ZC_KERNEL_MODE
      COMMON/zc_kernel_tape/KERNEL_NSST,KERNEL_ATM_ITER,
     A KERNEL_ATM_RESET

      ZC_KERNEL_MODE=.TRUE.
      KERNEL_NSST=-1
      KERNEL_ATM_ITER=-1
      KERNEL_ATM_RESET=-1
      NT=NT+1
      TD=TZERO+FLOAT(NT)*DTD
      IT1=TD+120.501
      IT=MOD(IT1,12)
      MP=IT+1
      IF(IT.EQ.0) IT=12
      TY=TD+120.501-IT1

      CALL SSTA(TD)
      ist=ist+1
      CALL ZATMC(TD)
      CALL STRESS(TD,ISTART)
      CALL CFORCE
      CALL MLOOP

      TAPE(1)=KERNEL_NSST
      TAPE(2)=KERNEL_ATM_ITER
      TAPE(3)=KERNEL_ATM_RESET
      RETURN
      END


      SUBROUTINE ZC_KERNEL_STEP(STATE_R_IN,STATE_C_IN,STATE_D_IN,
     A STATE_I_IN,STATE_TIME_IN,STATE_R_OUT,STATE_C_OUT,STATE_D_OUT,
     B STATE_I_OUT,STATE_TIME_OUT,TAPE)
      INCLUDE 'zc_kernel_state.inc'
      REAL STATE_R_IN(ZC_STATE_NREAL),STATE_R_OUT(ZC_STATE_NREAL)
      COMPLEX STATE_C_IN(ZC_STATE_NCOMPLEX)
      COMPLEX STATE_C_OUT(ZC_STATE_NCOMPLEX)
      REAL*8 STATE_D_IN(ZC_STATE_NDOUBLE)
      REAL*8 STATE_D_OUT(ZC_STATE_NDOUBLE)
      INTEGER STATE_I_IN(ZC_STATE_NINTEGER)
      INTEGER STATE_I_OUT(ZC_STATE_NINTEGER),TAPE(ZC_TAPE_WIDTH)
      REAL STATE_TIME_IN(ZC_STATE_NTIME),STATE_TIME_OUT(ZC_STATE_NTIME)

      CALL ZC_KERNEL_UNPACK(STATE_R_IN,STATE_C_IN,STATE_D_IN,
     A STATE_I_IN,STATE_TIME_IN)
      CALL ZC_KERNEL_ADVANCE_COMMON(TAPE)
      CALL ZC_KERNEL_PACK(STATE_R_OUT,STATE_C_OUT,STATE_D_OUT,
     A STATE_I_OUT,STATE_TIME_OUT)
      RETURN
      END


      SUBROUTINE ZC_KERNEL_WINDOW(STATE_R_IN,STATE_C_IN,STATE_D_IN,
     A STATE_I_IN,STATE_TIME_IN,NSTEPS,STATE_R_OUT,STATE_C_OUT,
     B STATE_D_OUT,STATE_I_OUT,STATE_TIME_OUT,TAPE)
      INCLUDE 'zc_kernel_state.inc'
      REAL STATE_R_IN(ZC_STATE_NREAL),STATE_R_OUT(ZC_STATE_NREAL)
      COMPLEX STATE_C_IN(ZC_STATE_NCOMPLEX)
      COMPLEX STATE_C_OUT(ZC_STATE_NCOMPLEX)
      REAL*8 STATE_D_IN(ZC_STATE_NDOUBLE)
      REAL*8 STATE_D_OUT(ZC_STATE_NDOUBLE)
      INTEGER STATE_I_IN(ZC_STATE_NINTEGER)
      INTEGER STATE_I_OUT(ZC_STATE_NINTEGER)
      INTEGER TAPE(ZC_TAPE_WIDTH,*)
      REAL STATE_TIME_IN(ZC_STATE_NTIME),STATE_TIME_OUT(ZC_STATE_NTIME)

      IF(NSTEPS.LT.0) THEN
         WRITE(6,'(A)')
     A    'ERROR: ZC kernel window requires NSTEPS >= 0'
         STOP 2
      ENDIF
      CALL ZC_KERNEL_UNPACK(STATE_R_IN,STATE_C_IN,STATE_D_IN,
     A STATE_I_IN,STATE_TIME_IN)
      DO 10 N=1,NSTEPS
         CALL ZC_KERNEL_ADVANCE_COMMON(TAPE(1,N))
 10   CONTINUE
      CALL ZC_KERNEL_PACK(STATE_R_OUT,STATE_C_OUT,STATE_D_OUT,
     A STATE_I_OUT,STATE_TIME_OUT)
      RETURN
      END


      SUBROUTINE ZC_PACK_REAL(A,N,X,K)
      REAL A(*),X(*)
      DO 10 I=1,N
         X(K)=A(I)
         K=K+1
 10   CONTINUE
      RETURN
      END

      SUBROUTINE ZC_UNPACK_REAL(A,N,X,K)
      REAL A(*),X(*)
      DO 10 I=1,N
         A(I)=X(K)
         K=K+1
 10   CONTINUE
      RETURN
      END

      SUBROUTINE ZC_PACK_COMPLEX(A,N,X,K)
      COMPLEX A(*),X(*)
      DO 10 I=1,N
         X(K)=A(I)
         K=K+1
 10   CONTINUE
      RETURN
      END

      SUBROUTINE ZC_UNPACK_COMPLEX(A,N,X,K)
      COMPLEX A(*),X(*)
      DO 10 I=1,N
         A(I)=X(K)
         K=K+1
 10   CONTINUE
      RETURN
      END

      SUBROUTINE ZC_PACK_REAL_2D(A,LDA,NROW,NCOL,X,K)
      REAL A(LDA,*),X(*)
      DO 20 J=1,NCOL
         DO 10 I=1,NROW
            X(K)=A(I,J)
            K=K+1
 10      CONTINUE
 20   CONTINUE
      RETURN
      END

      SUBROUTINE ZC_UNPACK_REAL_2D(A,LDA,NROW,NCOL,X,K)
      REAL A(LDA,*),X(*)
      DO 20 J=1,NCOL
         DO 10 I=1,NROW
            A(I,J)=X(K)
            K=K+1
 10      CONTINUE
 20   CONTINUE
      RETURN
      END
