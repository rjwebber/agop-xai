C=======================================================================
C Explicit-state deterministic wrapper for the authentic Zebiak--Cane
C forward model.  This file is linked only in the isolated kernel build.
C=======================================================================

      SUBROUTINE ZC_KERNEL_PACK(STATE_R,STATE_C,STATE_D,STATE_I,
     A STATE_TIME)
      INCLUDE 'zc_kernel_state.inc'
      INCLUDE 'zeq.common'
      INCLUDE 'modified_means.common'

      REAL STATE_R(ZC_STATE_NREAL)
      COMPLEX STATE_C(ZC_STATE_NCOMPLEX)
      REAL*8 STATE_D(ZC_STATE_NDOUBLE)
      INTEGER STATE_I(ZC_STATE_NINTEGER)
      REAL STATE_TIME(ZC_STATE_NTIME)

      COMMON/ZDATA/WM(30,34,2,12),DIVM(30,34,12),Q0O(30,34),
     A SSTM(30,34,12),UO(30,34),VO(30,34),DO(30,34),HTAU(34,30,2),
     B WEM(30,34,12),TO(30,34),UV(30,34,2,12),US(30,34),VS(30,34),
     C WP(30,34),DT1(30,34,7),TT(30,34),UV1(30,34),UV2(30,34),
     D WM1(30,34),UAT(30,34),VAT(30,34),DIVT(30,34)
      COMMON/ZDAT2/H1(30,34),U1(30,34),V1(30,34)
      REAL QF(30,34),QEO(30,64),DIF(16,34)
      COMMON/grads_atm/QF,QEO
      COMPLEX Q(80,64),E1(80),E2(80)
      COMMON/fresh_zatmc_state/DIF,Q,E1,E2,UBAR
      REAL*8 DSEED
      COMMON/fresh_stress_state/DSEED,T0,R
      COMMON/commTIME/IT,MP,TY

      IF(NXP.NE.79.OR.NYP.NE.116.OR.NSEG.NE.1) THEN
         WRITE(6,'(A)')
     A    'ERROR: ZC kernel only supports certified Standard grid'
         STOP 2
      ENDIF
      NS=NSEG+1
      K=1
      CALL ZC_PACK_REAL(AKB,NXP,STATE_R,K)
      CALL ZC_PACK_REAL_2D(UB,117,NYP,NXP,STATE_R,K)
      CALL ZC_PACK_REAL_2D(HB,117,NYP,NXP,STATE_R,K)
      CALL ZC_PACK_REAL(ABC,NS,STATE_R,K)
      CALL ZC_PACK_REAL(ROSS,NS,STATE_R,K)
      CALL ZC_PACK_REAL(TR,NS,STATE_R,K)
      CALL ZC_PACK_REAL_2D(V,117,NYP,NXP,STATE_R,K)
      CALL ZC_PACK_REAL_2D(UBNDY,117,NYP,NS,STATE_R,K)
      CALL ZC_PACK_REAL_2D(HBNDY,117,NYP,NS,STATE_R,K)

      CALL ZC_PACK_REAL(Q0O,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(UO,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(VO,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(DO,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(TO,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(U1,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(V1,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(H1,30*34,STATE_R,K)

      CALL ZC_PACK_REAL(HTAU,34*30*2,STATE_R,K)
      CALL ZC_PACK_REAL(US,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(VS,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(WP,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(DT1,30*34*7,STATE_R,K)
      CALL ZC_PACK_REAL(TT,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(UV1,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(UV2,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(WM1,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(UAT,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(VAT,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(DIVT,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(QF,30*34,STATE_R,K)
      CALL ZC_PACK_REAL(QEO,30*64,STATE_R,K)
      CALL ZC_PACK_REAL(DIF,16*34,STATE_R,K)
      CALL ZC_PACK_REAL(UBAR,1,STATE_R,K)
      CALL ZC_PACK_REAL(T0,1,STATE_R,K)
      CALL ZC_PACK_REAL(R,1,STATE_R,K)
      CALL ZC_PACK_REAL(time_of_last_initialization,1,STATE_R,K)
      CALL ZC_PACK_REAL(AK,NXP,STATE_R,K)
      IF(K.NE.ZC_STATE_NREAL+1) THEN
         WRITE(6,'(A)') 'ERROR: ZC real pack layout error'
         STOP 2
      ENDIF

      K=1
      CALL ZC_PACK_COMPLEX(Q,80*64,STATE_C,K)
      CALL ZC_PACK_COMPLEX(E1,80,STATE_C,K)
      CALL ZC_PACK_COMPLEX(E2,80,STATE_C,K)
      IF(K.NE.ZC_STATE_NCOMPLEX+1) THEN
         WRITE(6,'(A)') 'ERROR: ZC complex pack layout error'
         STOP 2
      ENDIF

      STATE_D(1)=DSEED
      STATE_I(1)=NT
      STATE_I(2)=IT
      STATE_I(3)=MP
      STATE_I(4)=ISTART
      STATE_TIME(1)=TD
      STATE_TIME(2)=TY
      RETURN
      END


